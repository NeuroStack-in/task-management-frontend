export interface NavItem {
  label: string;
  href: string;
  icon: LucideIcon;
  /** Permission required to see this item. null = always visible. */
  permission: PermissionId | null;
  /** If set, item is visible when the role holds ANY of these (overrides `permission` for visibility). */
  anyPermissions?: PermissionId[];
  /** Short description, shown in the Settings/admin hub or Insights tabs. */
  description?: string;
  /** Extra search synonyms (e.g. "mfa 2fa multifactor") so global search finds
   *  a section by what it contains, not just its label. */
  keywords?: string;
  /**
   * `false` keeps the entry out of the **sidebar** only. It still gates its route, titles its page
   * and is offered by global search — every other reader of the tree sees it as before. For a page
   * the chrome already reaches another way (Notifications: the bell, and its "View all" link).
   */
  inSidebar?: false;
}

export interface NavGroup {
  label: string;
  items: NavItem[];
  /**
   * `"footer"` pins the group's items to the foot of the sidebar, above the account rows, with no
   * heading — for the utility destinations every role has (Settings, Help) rather than a section of
   * work (UX audit 2026-10-16, SHELL-04).
   */
  placement?: "footer";
}

