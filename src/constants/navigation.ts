export interface NavItem {
  label: string;
  href: string;
  icon: LucideIcon;
  /** Permission required to see this item. null = always visible. */
  permission: PermissionId | null;
  /** If set, item is visible when the role holds ANY of these (overrides `permission` for visibility). */
  anyPermissions?: PermissionId[];
  /** Short description, shown in the Settings/admin hub or Insights tabs. */
  description?: string;
  /** Extra search synonyms (e.g. "mfa 2fa multifactor") so global search finds
   *  a section by what it contains, not just its label. */
  keywords?: string;
}

export interface NavGroup {
  label: string;
  items: NavItem[];
}

